def ell(cx, cy, rx, ry, n=40, a0=0.0, a1=2*math.pi):
    return [(cx + rx*math.cos(a0 + (a1-a0)*i/n), cy + ry*math.sin(a0 + (a1-a0)*i/n))
            for i in range(n+1)]

